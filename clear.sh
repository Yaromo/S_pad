#!/bin/bash

# Получаем текущую директорию, где запущен скрипт
TARGET_DIR=$(pwd)

echo "⚠️⚠️⚠️ ВНИМАНИЕ! ⚠️⚠️⚠️"
echo "Вы собираетесь УДАЛИТЬ ВСЁ содержимое в директории:"
echo "👉 $TARGET_DIR"
echo "Это действие удалит весь код, файлы настроек и виртуальное окружение БЕЗВОЗВРАТНО."
echo "------------------------------------------------"
read -p "Вы уверены? Введите 'yes' для подтверждения удаления: " CONFIRM

if [ "$CONFIRM" = "yes" ]; then
    echo "🧹 Начинаю полную очистку директории..."
    
    # Удаляем скрытые и обычные файлы/папки, кроме самого скрипта очистки (чтобы он не выдал ошибку в процессе)
    # Используем поиск, чтобы безопасно очистить содержимое
    find "$TARGET_DIR" -mindepth 1 -maxdepth 1 ! -name "clean.sh" -exec rm -rf {} +

    echo "✅ Директория очищена!"
else
    echo "❌ Очистка отменена. Ничего не удалено."
fi
