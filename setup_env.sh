#!/bin/bash

# Название папки виртуального окружения и файла зависимостей
ENV_DIR="myenv"
REQ_FILE="requirements.txt"

# 1. Проверяем наличие файла требований
if [ ! -f "$REQ_FILE" ]; then
    echo "❌ Ошибка: Файл $REQ_FILE не найден в текущей директории!"
    exit 1
fi

# 2. Проверяем и создаем виртуальное окружение, если его нет
if [ ! -d "$ENV_DIR" ]; then
    echo "📦 Виртуальное окружение не найдено. Создаю '$ENV_DIR'..."
    python3 -m venv "$ENV_DIR"
    if [ $? -ne 0 ]; then
        echo "❌ Ошибка при создании виртуального окружения. Проверьте, установлен ли python3-venv."
        exit 1
    fi
else
    echo "✅ Виртуальное окружение '$ENV_DIR' уже существует."
fi

# 3. Активируем виртуальное окружение
echo "🔄 Активация окружения..."
source "$ENV_DIR/bin/activate"

# 4. Проверяем, нужно ли обновлять/устанавливать библиотеки
echo "🔍 Проверка зависимостей..."

# Обновляем сам pip внутри окружения (опционально, но рекомендуется)
pip install --upgrade pip -q

# Проверяем соответствие установленных пакетов файлу requirements.txt
# С помощью pip check или сравнивая состав через pip sync / install
# Самый надежный и быстрый способ без лишней перезаписи:
if pip install -r "$REQ_FILE" --dry-run | grep -q "Would install"; then
    echo "📥 Найдены новые или изменившиеся библиотеки. Устанавливаю..."
    pip install -r "$REQ_FILE"
    echo "🎉 Все библиотеки успешно установлены/обновлены!"
else
    echo "😎 Все библиотеки уже установлены и соответствуют $REQ_FILE."
fi

echo "🚀 Виртуальное окружение готово к работе!"