#!/bin/bash

# 1. Запускаем проверку/создание окружения через source.
# Это гарантирует, что переменные среды активируются в текущей сессии скрипта.
if [ -f "./setup_env.sh" ]; then
    echo "🔄 Проверка и подготовка окружения..."
    source ./setup_env.sh
else
    echo "❌ Ошибка: Скрипт setup_env.sh не найден!"
    exit 1
fi

# 2. Проверяем наличие файла main.py
if [ ! -f "main.py" ]; then
    echo "❌ Ошибка: Файл main.py не найден в текущей директории!"
    exit 1
fi

# 3. Запускаем ваш Python-скрипт внутри активированной среды
echo "🖥️ Запуск main.py..."
python main.py

# Опционально: деактивируем окружение после завершения работы python
deactivate
